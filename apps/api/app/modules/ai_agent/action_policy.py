"""
Master Build 06 — AI Sales Agent Action Policy, State Models & Risk Tiers
========================================================================
Canonical definitions for:
  1. AgentState & CustomerJourneyState
  2. ActionRiskTier (LOW, MEDIUM, HIGH, CRITICAL)
  3. NextBestActionType & AutonomyLevel
  4. ProposedActionDTO
  5. ActionPolicyEngine (Deterministic enterprise policy & autonomy gates)

NON-NEGOTIABLE INVARIANTS:
  - LLMs NEVER decide policy or permissions.
  - Critical actions (booking, payments, cancellations) CANNOT be autonomous.
  - Every proposed action carries risk tier, evidence, confidence, and authorization rules.
"""
